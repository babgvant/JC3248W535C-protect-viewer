"""Regenerate firmware/main/font_data.c: antialiased 10x20 ASCII glyphs from Cascadia Mono (SIL OFL 1.1).
Usage: python tools/gen_font.py [path/to/CascadiaMono.ttf]"""
import sys
from PIL import Image, ImageDraw, ImageFont
W, H, BASE, SIZE = 10, 20, 15, 17
path = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\Fonts\CascadiaMono.ttf"
font = ImageFont.truetype(path, SIZE)
rows = []
for code in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, BASE), chr(code), fill=255, font=font, anchor="ls")
    px = list(img.getdata())
    rows.append("    {" + ",".join(str(p >> 4) for p in px) + "}, /* %r */" % chr(code).replace("*", "star"))
out = ("// Generated by tools/gen_font.py from Cascadia Mono (SIL Open Font License 1.1). 4-bit alpha, 10x20 cells.\n"
       "#include <stdint.h>\nconst uint8_t font_alpha[95][%d]={\n" % (W * H)) + "\n".join(rows) + "\n};\n"
open("firmware/main/font_data.c", "w", encoding="utf-8").write(out)
